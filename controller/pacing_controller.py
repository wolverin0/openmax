@dataclass
class PacingConfig:
    """Configuration for PacingController slow-loop optimization."""

    iface: str = "eth0"
    latency_target_ms: float = 25.0
    bloat_threshold_ms: float = 15.0
    shaper_headroom_pct: float = 0.90
    min_shaper_mbps: float = 5.0
    max_shaper_mbps: float = 300.0
    baseline_ampdu: int = 64
    min_ampdu: int = 8
    baseline_amsdu: int = 3
    diffserv: str = "diffserv4"
    rtt_target: str = "100ms"
    retry_threshold_pct: float = 8.0
    snr_low_threshold_db: float = 20.0
    snr_high_threshold_db: float = 27.0
    safety_max_loss_pct: float = 15.0
    dry_run: bool = True
    state_file: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class StationControlAction:
    """Per-station control decisions for aggregation and rate override."""

    mac: str
    ampdu_limit: int
    amsdu_limit: int
    htt_aggr_word: int
    htt_aggr_hex: str
    max_mcs: int
    mask_hex: str
    rate_override_frame: bytes
    rate_override_hex: str
    bandwidth_mhz: int
    nss: int
    throttle_reason: str

    def to_dict(self) -> Dict[str, Any]:
        d = asdict(self)
        d["rate_override_frame"] = self.rate_override_hex
        return d


@dataclass
class PacingAction:
    """Unified control action generated by the slow-loop manager."""

    timestamp: str
    shaper_bandwidth_mbps: float
    shaper_bandwidth_str: str
    cake_commands: List[str]
    station_actions: Dict[str, StationControlAction]
    is_throttled: bool
    is_rollback: bool
    safety_alerts: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "timestamp": self.timestamp,
            "shaper_bandwidth_mbps": self.shaper_bandwidth_mbps,
            "shaper_bandwidth_str": self.shaper_bandwidth_str,
            "cake_commands": self.cake_commands,
            "station_actions": {k: v.to_dict() for k, v in self.station_actions.items()},
            "is_throttled": self.is_throttled,
            "is_rollback": self.is_rollback,
            "safety_alerts": self.safety_alerts,
        }


class PacingController:
    """Active Slow-Loop Pacing and Bufferbloat Manager.

    Evaluates network health and bufferbloat metrics, adjusts host CAKE shaping,
    throttles hardware A-MPDU limits to reduce radio queue residency, and imposes
    rate mask bounds on degraded links.
    """

    def __init__(self, config: Optional[PacingConfig] = None):
        self.config = config or PacingConfig()
        self.station_bandits: Dict[str, ADRBanditRateController] = {}
        self.history: List[Dict[str, Any]] = []
        self.last_action: Optional[PacingAction] = None

        # Load persisted state if configured
        if self.config.state_file:
            self.load_state(self.config.state_file)

    def _get_or_create_bandit(self, mac: str) -> ADRBanditRateController:
        """Retrieve or initialize ADRBanditRateController for a CPE."""
        if mac not in self.station_bandits:
            self.station_bandits[mac] = ADRBanditRateController(cpe_id=mac)
        return self.station_bandits[mac]

    def _normalize_station_telemetry(
        self,
        telemetry_input: Union[Dict[str, Any], List[Any], Any],
    ) -> Dict[str, Dict[str, Any]]:
        """Normalize various station telemetry inputs into a standard dictionary."""
        stations: Dict[str, Dict[str, Any]] = {}

        if hasattr(telemetry_input, "stations"):
            # StationSectorSummary instance
            raw_stations = telemetry_input.stations
            for mac, st in raw_stations.items():
                stations[mac] = st.to_dict() if hasattr(st, "to_dict") else dict(st)
        elif isinstance(telemetry_input, dict):
            if "stations" in telemetry_input:
                for mac, st in telemetry_input["stations"].items():
                    stations[mac] = st.to_dict() if hasattr(st, "to_dict") else dict(st)
            else:
                for k, v in telemetry_input.items():
                    if isinstance(v, dict) or hasattr(v, "to_dict"):
                        mac = v.get("mac", k) if isinstance(v, dict) else getattr(v, "mac", k)
                        stations[mac] = v.to_dict() if hasattr(v, "to_dict") else dict(v)
        elif isinstance(telemetry_input, list):
            for st in telemetry_input:
                d = st.to_dict() if hasattr(st, "to_dict") else dict(st)
                mac = d.get("mac", f"unknown-{len(stations)}")
                stations[mac] = d

        return stations

    def _normalize_bufferbloat(
        self,
        bb_input: Optional[Union[Dict[str, Any], LatencyStats, BufferbloatResult]],
    ) -> Dict[str, Any]:
        """Normalize bufferbloat metrics into a standard dictionary."""
        if bb_input is None:
            return {
                "p50_ms": 1.5,
                "p95_ms": 2.0,
                "p99_ms": 3.0,
                "bloat_p95_ms": 0.5,
                "goodput_mbps": 80.0,
                "loss_pct": 0.0,
            }

        if hasattr(bb_input, "to_dict"):
            d = bb_input.to_dict()
        elif isinstance(bb_input, dict):
            d = bb_input
        else:
            d = {}

        p50 = d.get("p50_ms", 2.0)
        p95 = d.get("p95_ms", 5.0)
        p99 = d.get("p99_ms", 8.0)
        bloat_p95 = d.get("bloat_p95_ms", d.get("bloat_delta_ms", max(0.0, p95 - p50)))
        goodput = d.get("goodput_mbps", 80.0)
        loss = d.get("loss_pct", d.get("packet_loss_pct", 0.0))

        # Check loaded_stats subdict if present
        if "loaded_stats" in d and isinstance(d["loaded_stats"], dict):
            ls = d["loaded_stats"]
            p50 = ls.get("p50_ms", p50)
            p95 = ls.get("p95_ms", p95)
            p99 = ls.get("p99_ms", p99)
            loss = ls.get("loss_pct", ls.get("packet_loss_pct", loss))

        return {
            "p50_ms": float(p50 or 2.0),
            "p95_ms": float(p95 or 5.0),
            "p99_ms": float(p99 or 8.0),
            "bloat_p95_ms": float(bloat_p95 or 0.0),
            "goodput_mbps": float(goodput or 80.0),
            "loss_pct": float(loss or 0.0),
        }

    def evaluate(
        self,
        station_telemetry: Union[Dict[str, Any], List[Any], Any],
        bufferbloat: Optional[Union[Dict[str, Any], LatencyStats, BufferbloatResult]] = None,
    ) -> PacingAction:
        """Run slow-loop evaluation and generate unified control decisions."""
        ts = dt.datetime.now(dt.timezone.utc).isoformat()
        stations = self._normalize_station_telemetry(station_telemetry)
        bb = self._normalize_bufferbloat(bufferbloat)

        alerts: List[str] = []
        is_throttled = False

        # 1. Evaluate Bufferbloat Severity
        loaded_p95 = bb["p95_ms"]
        bloat_delta = bb["bloat_p95_ms"]
        packet_loss = bb["loss_pct"]

        # Check safety thresholds
        if packet_loss > self.config.safety_max_loss_pct:
            alerts.append(f"Excessive packet loss detected: {packet_loss}% > {self.config.safety_max_loss_pct}%")

        latency_violation = (loaded_p95 > self.config.latency_target_ms) or (
            bloat_delta > self.config.bloat_threshold_ms
        )

        # 2. Compute CAKE Shaper Bandwidth
        # Estimate total capacity from station PHY bitrates or bufferbloat goodput
        reported_rates = [
            float(st.get("tx_rate_mbps", 0.0) or 0.0)
            for st in stations.values()
            if float(st.get("tx_rate_mbps", 0.0) or 0.0) > 0.0
        ]
        if reported_rates:
            # Bottleneck capacity approximation
            sector_capacity = sum(reported_rates) / max(1, len(reported_rates))
        else:
            sector_capacity = bb["goodput_mbps"] or 80.0

        shaper_bandwidth = sector_capacity * self.config.shaper_headroom_pct

        # If latency is violated, apply backoff to drain wireless queues into CAKE
        if latency_violation:
            is_throttled = True
            if bloat_delta > 50.0:
                backoff_factor = 0.70
                alerts.append(f"Severe bufferbloat ({bloat_delta:.1f}ms): Shaper throttled to 70%")
            elif bloat_delta > 25.0:
                backoff_factor = 0.80
                alerts.append(f"Moderate bufferbloat ({bloat_delta:.1f}ms): Shaper throttled to 80%")
            else:
                backoff_factor = 0.88
            shaper_bandwidth *= backoff_factor

        # Clamp bandwidth to safe limits
        shaper_bandwidth = max(
            self.config.min_shaper_mbps,
            min(self.config.max_shaper_mbps, round(shaper_bandwidth, 1)),
        )
        shaper_bw_str = f"{int(shaper_bandwidth)}Mbit"

        # Generate CAKE commands
        cake_cmds = generate_cake_commands(
            iface=self.config.iface,
            bandwidth=shaper_bw_str,
            diffserv=self.config.diffserv,
            rtt=self.config.rtt_target,
            ack_filter=True,
            wash=True,
        )

        # 3. Compute Per-CPE Control Actions (Aggregation + Rate Constraints)
        station_actions: Dict[str, StationControlAction] = {}

        for mac, st in stations.items():
            # A. Aggregation Control (A-MPDU Throttling)
            if latency_violation:
                if bloat_delta > 50.0:
                    ampdu = self.config.min_ampdu  # e.g. 8
                    reason = f"Aggressive throttle: bloat delta {bloat_delta:.1f}ms > 50ms"
                elif bloat_delta > 25.0:
                    ampdu = max(self.config.min_ampdu, 16)
                    reason = f"Moderate throttle: bloat delta {bloat_delta:.1f}ms > 25ms"
                else:
                    ampdu = max(self.config.min_ampdu, 32)
                    reason = f"Light throttle: loaded latency {loaded_p95:.1f}ms > target"
            else:
                ampdu = self.config.baseline_ampdu  # 64 subframes
                reason = "Optimal latency: baseline aggregation enabled"

            amsdu = self.config.baseline_amsdu  # 3 subframes
            policy = AggregationPolicy(amsdu=amsdu, ampdu=ampdu)
            htt_word = policy.to_htt_word()
            htt_hex = policy.to_htt_hex()

            # B. Rate Constraint & Dead MCS Avoidance
            snr = float(st.get("snr_db", 25.0) or 25.0)
            retries = int(st.get("tx_retries", 0) or 0)
            tx_packets = int(st.get("tx_packets", 0) or 0)
            retry_pct = (retries / tx_packets * 100.0) if tx_packets > 0 else float(retries)

            bw = int(st.get("bandwidth_mhz", 20) or 20)
            nss = int(st.get("nss", 1) or 1)
            # Default to 2SS if hardware indicates 2 chains
            if st.get("chain1_signal_dbm") is not None:
                nss = 2

            bandit = self._get_or_create_bandit(mac)

            # Dead-MCS bounding based on wireless channel conditions
            if retry_pct > self.config.retry_threshold_pct or snr < self.config.snr_low_threshold_db:
                # Poor channel: ban 256-QAM (MCS 8-9) and 64-QAM if severe
                if snr < 15.0:
                    arm = bandit.arms[4]  # MCS0-3 (QPSK)
                elif snr < self.config.snr_low_threshold_db:
                    arm = bandit.arms[3]  # MCS0-5 (16-QAM)
                else:
                    arm = bandit.arms[2]  # MCS0-7 (64-QAM Ceiling)
                rate_reason = f"Retry/SNR constraint: {retry_pct:.1f}% retries, SNR {snr:.1f}dB"
            elif snr < self.config.snr_high_threshold_db:
                # Moderate channel: Ban MCS9 (256-QAM 5/6 rate)
                arm = bandit.arms[1]  # MCS0-8
                rate_reason = f"Marginal SNR ({snr:.1f}dB): Ban MCS9"
            else:
                # Clean channel: allow bandit selection or full MCS0-9
                arm = bandit.select_arm()
                rate_reason = f"Clean channel ({snr:.1f}dB): Bandit {arm.name}"

            rate_frame = arm.to_rate_override_frame(bw=bw, nss=nss)

            station_actions[mac] = StationControlAction(
                mac=mac,
                ampdu_limit=ampdu,
                amsdu_limit=amsdu,
                htt_aggr_word=htt_word,
                htt_aggr_hex=htt_hex,
                max_mcs=arm.max_mcs,
                mask_hex=arm.mask_hex,
                rate_override_frame=rate_frame,
                rate_override_hex=rate_frame.hex(),
                bandwidth_mhz=bw,
                nss=nss,
                throttle_reason=f"{reason} | {rate_reason}",
            )

        action = PacingAction(
            timestamp=ts,
            shaper_bandwidth_mbps=shaper_bandwidth,
            shaper_bandwidth_str=shaper_bw_str,
            cake_commands=cake_cmds,
            station_actions=station_actions,
            is_throttled=is_throttled,
            is_rollback=False,
            safety_alerts=alerts,
        )

        self.last_action = action
        self.history.append(action.to_dict())

        if self.config.state_file:
            self.save_state()

        return action

    def rollback(self) -> PacingAction:
        """Rollback all throttling and rate constraints to safe baseline."""
        ts = dt.datetime.now(dt.timezone.utc).isoformat()
        alerts = ["Rollback safeguard executed: Restoring default aggregation and shaper."]

        # Restore max shaper
        shaper_bw = self.config.max_shaper_mbps
        shaper_bw_str = f"{int(shaper_bw)}Mbit"
        cake_cmds = generate_cake_commands(
            iface=self.config.iface,
            bandwidth=shaper_bw_str,
            diffserv=self.config.diffserv,
            rtt=self.config.rtt_target,
        )

        station_actions: Dict[str, StationControlAction] = {}
        for mac, bandit in self.station_bandits.items():
            # Reset to baseline 64 AMPDU
            policy = AggregationPolicy(
                amsdu=self.config.baseline_amsdu,
                ampdu=self.config.baseline_ampdu,
            )
            # Reset to unbounded MCS0-9
            arm = bandit.arms[0]
            rate_frame = arm.to_rate_override_frame(bw=20, nss=1)

            station_actions[mac] = StationControlAction(
                mac=mac,
                ampdu_limit=self.config.baseline_ampdu,
                amsdu_limit=self.config.baseline_amsdu,
                htt_aggr_word=policy.to_htt_word(),
                htt_aggr_hex=policy.to_htt_hex(),
                max_mcs=arm.max_mcs,
                mask_hex=arm.mask_hex,
                rate_override_frame=rate_frame,
                rate_override_hex=rate_frame.hex(),
                bandwidth_mhz=20,
                nss=1,
                throttle_reason="Rollback safeguard: baseline parameters restored",
            )

        action = PacingAction(
            timestamp=ts,
            shaper_bandwidth_mbps=shaper_bw,
            shaper_bandwidth_str=shaper_bw_str,
            cake_commands=cake_cmds,
            station_actions=station_actions,
            is_throttled=False,
            is_rollback=True,
            safety_alerts=alerts,
        )

        self.last_action = action
        self.history.append(action.to_dict())

        if self.config.state_file:
            self.save_state()

        return action

    def apply(self, action: PacingAction) -> bool:
        """Apply a pacing control action.

        Respects config.dry_run: logs commands without calling kernel if dry_run=True.
        """
        if self.config.dry_run:
            logger.info("[DRY-RUN] Pacing action generated successfully (kernel execution skipped).")
            for cmd in action.cake_commands:
                logger.debug(f"[DRY-RUN tc] {cmd}")
            for mac, sa in action.station_actions.items():
                logger.debug(
                    f"[DRY-RUN station {mac}] A-MPDU={sa.ampdu_limit}, HTT={sa.htt_aggr_hex}, "
                    f"MCS={sa.max_mcs}, WireFrame={sa.rate_override_hex}"
                )
            return True

        # Non-dry-run live application
        try:
            for cmd in action.cake_commands:
                subprocess.run(cmd, shell=True, check=True, timeout=5)
            return True
        except Exception as exc:
            logger.error(f"Failed to apply CAKE commands live: {exc}")
            return False

    def save_state(self, filepath: Optional[str] = None) -> None:
        """Persist slow-loop controller state and bandit statistics to JSON."""
        target_path = Path(filepath or self.config.state_file or "pacing_controller_state.json")
        target_path.parent.mkdir(parents=True, exist_ok=True)

        state_data = {
            "config": self.config.to_dict(),
            "last_action": self.last_action.to_dict() if self.last_action else None,
            "bandits": {
                mac: bandit.get_status() for mac, bandit in self.station_bandits.items()
            },
            "history_count": len(self.history),
            "updated_at": dt.datetime.now(dt.timezone.utc).isoformat(),
        }

        with open(target_path, "w", encoding="utf-8") as f:
            json.dump(state_data, f, indent=2)

    def load_state(self, filepath: Optional[str] = None) -> bool:
        """Load controller state from JSON file."""
        target_path = Path(filepath or self.config.state_file or "pacing_controller_state.json")
        if not target_path.exists():
            return False

        try:
            with open(target_path, "r", encoding="utf-8") as f:
                data = json.load(f)

            if "config" in data:
                # Update non-runtime fields
                for k, v in data["config"].items():
                    if hasattr(self.config, k):
                        setattr(self.config, k, v)
            return True
        except Exception as exc:
            logger.warning(f"Could not load state from {target_path}: {exc}")
            return False

"""Active Slow-Loop Pacing and Bufferbloat Controller for FuturaMAX.

Integrates:
1. Linux CAKE / FQ-CoDel traffic shaping and DiffServ4 tin allocation.
2. Per-CPE A-MPDU / A-MSDU aggregation limits compiled into binary HTT Type 5 words.
3. Adaptive rate mask constraints and dead-MCS avoidance compiled into airMAX Subtype 0x1E frames.
4. Autonomous slow-loop adaptation with state persistence and rollback safeguards.
"""

